// @vitest-environment edge-runtime
import { convexTest } from 'convex-test';
import { describe, expect, it } from 'vitest';

import { api } from './_generated/api';
import schema from './schema';
import { basicTemplate } from './templates/basic';

const modules = import.meta.glob('./**/*.ts');

const TEST_USER = 'test-user-123';

/**
 * `simulationSettings.asOfDate` (parity plan P2-P0) has to survive a real Convex write.
 * These tests go through `api.simulation_settings.update`, so the argument validator and the
 * `plans` table validator both see the field.
 */
async function createPlan(t: ReturnType<typeof convexTest>) {
  return t.run(async (ctx) => ctx.db.insert('plans', { ...basicTemplate, userId: TEST_USER, name: 'Test Plan', isDefault: true }));
}

/** Reads `simulationSettings` the way a client does; cast because `Doc<'plans'>` is regenerated by codegen. */
async function readSimulationSettings(t: ReturnType<typeof convexTest>, planId: Awaited<ReturnType<typeof createPlan>>) {
  const plan = await t.run(async (ctx) => ctx.db.get(planId));
  return plan!.simulationSettings as { asOfDate?: string; simulationSeed: number; simulationMode: string };
}

describe('simulation_settings.update asOfDate', () => {
  it('persists a pinned as-of date and returns it from the query', async () => {
    const t = convexTest(schema, modules);
    const planId = await createPlan(t);
    const asUser = t.withIdentity({ subject: TEST_USER });

    await asUser.mutation(api.simulation_settings.update, {
      planId,
      simulationSettings: { ...basicTemplate.simulationSettings, asOfDate: '2026-03-15' },
    });

    expect((await readSimulationSettings(t, planId)).asOfDate).toBe('2026-03-15');
    await expect(asUser.query(api.simulation_settings.get, { planId })).resolves.toMatchObject({ asOfDate: '2026-03-15' });
  });

  it('still accepts settings without asOfDate, so plans saved before clock injection keep working', async () => {
    const t = convexTest(schema, modules);
    const planId = await createPlan(t);
    const asUser = t.withIdentity({ subject: TEST_USER });

    await asUser.mutation(api.simulation_settings.update, {
      planId,
      simulationSettings: { ...basicTemplate.simulationSettings },
    });

    const stored = await readSimulationSettings(t, planId);
    expect(stored.asOfDate).toBeUndefined();
    expect(stored.simulationSeed).toBe(basicTemplate.simulationSettings.simulationSeed);
  });

  it('rejects a non-string as-of date', async () => {
    const t = convexTest(schema, modules);
    const planId = await createPlan(t);
    const asUser = t.withIdentity({ subject: TEST_USER });

    await expect(
      asUser.mutation(api.simulation_settings.update, {
        planId,
        simulationSettings: { ...basicTemplate.simulationSettings, asOfDate: 20260315 as unknown as string },
      })
    ).rejects.toThrow();
  });
});
